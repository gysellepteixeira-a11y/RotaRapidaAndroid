def replace_once(old,new,desc):
    global s
    n=s.count(old)
    if n!=1:
        raise RuntimeError(f"V71 diagnostic {desc}: expected one anchor, found {n}")
    s=s.replace(old,new,1)

report_anchor='    private fun idReport(route:RouteResult){'
helper=r'''    // V71: sampled after sending, so these observations are not a direct
    // measurement of CPU frequency or of ML Kit's worker threads.
    // Read-only data only; never blocks or modifies OCR/send decisions.
    private fun perfSystemSnapshotV71(): String {
        var powerSave="?"
        var thermal="?"
        var batteryPct="?"
        var batteryC="?"
        var charging="?"
        var freeMemMb="?"
        var lowMem="?"
        var javaHeapMb="?"
        try {
            val pm=getSystemService(android.content.Context.POWER_SERVICE)
                as? android.os.PowerManager
            if(pm != null) {
                powerSave=pm.isPowerSaveMode.toString()
                thermal=pm.currentThermalStatus.toString()
            }
        } catch (_:Throwable) {}
        try {
            val b=registerReceiver(
                null,android.content.IntentFilter(android.content.Intent.ACTION_BATTERY_CHANGED)
            )
            if(b!=null) {
                val lvl=b.getIntExtra(android.os.BatteryManager.EXTRA_LEVEL,-1)
                val scale=b.getIntExtra(android.os.BatteryManager.EXTRA_SCALE,-1)
                if(lvl>=0 && scale>0) batteryPct=((lvl*100)/scale).toString()
                val temp=b.getIntExtra(android.os.BatteryManager.EXTRA_TEMPERATURE,-1)
                if(temp>=0) batteryC=(temp/10).toString()+"."+(temp%10).toString()
                val state=b.getIntExtra(android.os.BatteryManager.EXTRA_STATUS,-1)
                charging=(state==android.os.BatteryManager.BATTERY_STATUS_CHARGING ||
                    state==android.os.BatteryManager.BATTERY_STATUS_FULL).toString()
            }
        } catch (_:Throwable) {}
        try {
            val am=getSystemService(android.content.Context.ACTIVITY_SERVICE)
                as? android.app.ActivityManager
            if(am!=null){
                val mi=android.app.ActivityManager.MemoryInfo()
                am.getMemoryInfo(mi)
                freeMemMb=(mi.availMem/(1024L*1024L)).toString()
                lowMem=mi.lowMemory.toString()
            }
            val rt=Runtime.getRuntime()
            javaHeapMb=((rt.totalMemory()-rt.freeMemory())/(1024L*1024L)).toString()
        } catch (_:Throwable) {}
        return "V71 SISTEMA APOS ENVIO | bateria=$batteryPct% | bateriaTemp=$batteryC C"+
            " | carregando=$charging | economizador=$powerSave | thermalStatus=$thermal"+
            " | RAMlivre=$freeMemMb MB | poucaRAM=$lowMem | heapJava=$javaHeapMb MB"+
            " | nota=amostra apos envio, nao durante inferencia"
    }

'''
